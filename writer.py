import json

from pydantic import BaseModel, Field

from llm import generate
from reviewer import review

SYSTEM_PROMPT = """
تو نویسنده‌ی کاروسل یک پیج اینستاگرام روانشناسی برای مخاطب عمومی فارسی‌زبان هستی.
یک ایده‌ی تأییدشده و یک هوک انتخاب‌شده می‌گیری و متن اسلایدها را می‌نویسی.

ساختار:
- بین ۷ تا ۱۰ اسلاید.
- اسلاید ۱: دقیقاً همان هوک داده‌شده، بدون تغییر.
- اسلاید ۲: چرا این موضوع به زندگی مخاطب ربط دارد.
- اسلایدهای میانی: توضیح مفهوم، با یک مثال روزمره و آشنا برای مخاطب فارسی‌زبان.
- اگر هوک قول چیزی داده (مثلاً «۳ روش»)، دقیقاً همان را تحویل بده.
- یکی مانده به آخر: جمع‌بندی در یک جمله.
- اسلاید آخر: دعوت به ذخیره کردن، فرستادن برای یک دوست یا فالو.

قوانین محتوا:
- فقط از اطلاعات ایده‌ی داده‌شده استفاده کن و ادعای علمی تازه نساز.
- قطعیت را بیشتر از «میزان اطمینان» و «نکته‌ی احتیاط» ایده نکن.
  برای یافته‌ها بنویس «پژوهش‌ها نشان می‌دهند»، نه «ثابت شده».
- نظریه‌ها را با نام صاحبشان بیاور، نه به‌عنوان واقعیت قطعی.
- برچسب تشخیصی به مخاطب نزن و توصیه‌ی دارویی نکن.
- لحن صمیمی و محاوره‌ای.

قوانین شکل:
- اسلاید ۱ تیتر ندارد: title را خالی بگذار ("") و هوک را در body بنویس.
- تیتر هر اسلاید خودش یک حرف کامل است، نه برچسب بخش. حداکثر ۸ کلمه.
  بد: «جمع‌بندی» / «آشنایی با مفهوم علمی»
  خوب: «مغزت با خودِ آینده‌ت غریبگی می‌کنه»
- متن هر اسلاید حداکثر ۴۰ کلمه.
- همه‌ی اسلایدها محاوره‌ای و خطاب به «تو»، مثل حرف زدن با یک دوست.
  بد: «این عادت باعث می‌شود کارهای مهم انباشته شوند.»
  خوب: «نتیجه‌ش؟ کارا روی هم تلنبار می‌شن و تو می‌مونی و یه عالمه استرس.»
- حداقل یک اسلاید یک کار عملی و کوچیک بده که مخاطب همین امروز بتونه انجامش بده،
  فقط از راهکارهایی که در ایده آمده یا مستقیماً از خود مفهوم نتیجه می‌شود.
- هر اصطلاحی را اولین بار که می‌آوری، در همان اسلاید با زبان ساده توضیح بده.
- بدون علامت ** یا ایموجی.
"""


class Slide(BaseModel):
    title: str = Field(description="تیتر کوتاه اسلاید، حداکثر ۸ کلمه")
    body: str = Field(description="متن اسلاید، حداکثر ۴۰ کلمه")


class Carousel(BaseModel):
    slides: list[Slide]
    caption: str = Field(
        description="کپشن پست، ۲ تا ۳ جمله، با ۵ تا ۸ هشتگ فارسی در آخر")


def write_carousel(idea, hook, rounds=3, on_progress=print):
    """نویسنده + حلقه‌ی بازبینی. خروجی: (کاروسل، ایرادهای باقی‌مانده، مدل‌ها)"""
    base_request = (
        f"ایده:\n{json.dumps(idea, ensure_ascii=False, indent=2)}\n\n"
        f"هوک انتخاب‌شده:\n{hook}"
    )
    request = base_request
    issues, models = [], {}

    for round_no in range(1, rounds + 1):
        on_progress(f"دور {round_no}: نویسنده دارد می‌نویسد...")
        response = generate(request, SYSTEM_PROMPT, schema=Carousel)
        carousel = response.parsed.model_dump()
        models["writer"] = response.model_version

        on_progress(f"دور {round_no}: بازبین دارد چک می‌کند...")
        issues, models["reviewer"] = review(idea, carousel, hook)
        on_progress(f"دور {round_no}: بازبین {len(issues)} ایراد پیدا کرد.")

        if not issues:
            break

        request = (
            base_request
            + "\n\nنسخه‌ی قبلی تو:\n"
            + json.dumps(carousel, ensure_ascii=False, indent=2)
            + "\n\nبازبین این ایرادها را گرفته. فقط همین‌ها را اصلاح کن و بقیه را نگه دار:\n"
            + json.dumps(issues, ensure_ascii=False, indent=2)
        )

    return carousel, issues, models
