from dotenv import load_dotenv
from google import genai
from google.genai import types

load_dotenv()
client = genai.Client(http_options={"timeout": 60000})

SYSTEM_PROMPT = """
تو هوک‌نویس یک پیج اینستاگرام روانشناسی فارسی‌زبان هستی.
هوک، جمله‌ی اسلاید اول کاروسل است که باید مخاطب را در یک ثانیه نگه دارد تا ورق بزند.

قوانین نوشتن هوک:
- دست بگذار روی یکی از این‌ها: یک احساس ملموس، یک تجربه‌ی مشترک، یا یک اشتباه رایج.
- لحن صمیمی و محاوره‌ای (مثلاً «می‌کنی» نه «می‌کنید»).
- حداکثر ۱۲ کلمه.
- هیچ ادعای علمی یا پزشکی نکن و برچسب تشخیصی به مخاطب نزن.
- ۵ هوک باید از ۵ نوع مختلف باشند، به این ترتیب:
  ۱. احساس ملموس (توصیف یک حس بدنی یا ذهنی)
  ۲. تجربه‌ی مشترک (موقعیتی که مخاطب حتماً تجربه کرده)
  ۳. اشتباه رایج (یک باور غلط که مخاطب دارد و اصلاحش می‌کنی)
  ۴. عدد و وعده (مثلاً «۳ کاری که...»)
  ۵. جمله‌ی تکان‌دهنده یا غیرمنتظره
- حداکثر ۲ هوک می‌تواند سؤالی باشد. بقیه جمله‌ی خبری باشند.
قوانین شکل جواب:
- فقط ۵ هوک بنویس، هر کدام در یک خط.
- هیچ عنوان، شماره، توضیح، علامت ** یا متن اضافه‌ای ننویس.
"""

topic = "اضطراب اجتماعی"

response = client.models.generate_content(
    model="gemini-3.5-flash",
    contents=f"موضوع: {topic}",
    config=types.GenerateContentConfig(system_instruction=SYSTEM_PROMPT),
)

with open("output_v2.txt", "w", encoding="utf-8") as f:
    f.write(response.text)

print("ذخیره شد: output_v2.txt")